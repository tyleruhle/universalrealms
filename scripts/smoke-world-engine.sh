#!/bin/bash
# World Engine smoke test against a running server, using its real storage, engine and Claude key.
# Signs a short-lived token for a throwaway user, builds a small world end to end, then deletes it.
#
#   cd ~/universal-realms && bash scripts/smoke-world-engine.sh [base-url]     (default http://127.0.0.1:3000)
set -uo pipefail
cd "$(dirname "$0")/.."
BASE=${1:-http://127.0.0.1:3000}
TOKEN=$(node -e "require('dotenv').config(); console.log(require('jsonwebtoken').sign({userId: 'smoke-test', username: 'smoke-test'}, process.env.JWT_SECRET, {expiresIn: '15m'}))") || exit 1
pass=0; fail=0
ok()  { echo "  ok    $1"; pass=$((pass + 1)); }
bad() { echo "  FAIL  $1"; fail=$((fail + 1)); }
api() { curl -s -m 120 -H "Cookie: ur_token=$TOKEN" -H 'content-type: application/json' -X "$1" "$BASE$2" ${3:+-d "$3"}; }
field() { python3 -c "import json,sys; d=json.load(sys.stdin); print(d.get('$1', ''))" 2>/dev/null; }
wait_job() {   # world, job → final status
  for _ in $(seq 1 120); do
    s=$(api GET "/api/worlds/$1/jobs/$2" | field status)
    case "$s" in done|failed) echo "$s"; return ;; esac
    sleep 2
  done; echo timeout
}

echo "World Engine smoke test → $BASE"
code=$(curl -s -o /dev/null -w '%{http_code}' "$BASE/worlds.html"); [ "$code" = 200 ] && ok "worlds.html loads" || bad "worlds.html answered $code"
code=$(curl -s -o /dev/null -w '%{http_code}' "$BASE/api/worlds"); [ "$code" = 401 ] && ok "API refuses signed-out requests" || bad "signed-out API answered $code"

W=$(api POST /api/worlds '{"name":"Smoke test (safe to delete)"}' | field worldId)
[ -n "$W" ] && ok "world created in DynamoDB ($W)" || { bad "could not create a world (check WORLD_DB, table ur_worlds, IAM)"; exit 1; }

[ "$(api PUT "/api/worlds/$W/bible/overview" '{"text":"A dry world.","status":"confirmed"}' | python3 -c "import json,sys; print(json.load(sys.stdin)['sections']['overview']['status'])" 2>/dev/null)" = confirmed ] \
  && ok "bible saved to S3" || bad "bible save failed (check WORLD_STORE, WORLD_BUCKET, IAM)"

if [ "$(api GET /api/worlds/meta | field loreConfigured)" = True ]; then
  r=$(api POST "/api/worlds/$W/lore/message" '{"text":"In one sentence: what should we decide first about this world?"}' | field reply)
  [ -n "$r" ] && ok "Claude answered: ${r:0:80}…" || bad "Claude did not answer (check ANTHROPIC_API_KEY)"
else
  bad "lore not configured: ANTHROPIC_API_KEY is empty in .env"
fi

J=$(api POST "/api/worlds/$W/map" '{"brief":"arid mountainous world, fractured kingdoms","size":"small","seed":606}' | field jobId)
[ "$(wait_job "$W" "$J")" = done ] && ok "map generated by the Python engine" || bad "map job failed: $(api GET "/api/worlds/$W/jobs/$J" | field error)"
code=$(curl -s -o /dev/null -w '%{http_code}' -H "Cookie: ur_token=$TOKEN" "$BASE/api/worlds/$W/map/preview.png"); [ "$code" = 200 ] && ok "map preview served" || bad "preview answered $code"

J=$(api POST "/api/worlds/$W/history" '{"turns":6,"years":25,"seed":1}' | field jobId)
[ "$(wait_job "$W" "$J")" = done ] && ok "history simulated" || bad "history job failed: $(api GET "/api/worlds/$W/jobs/$J" | field error)"

[ "$(api DELETE "/api/worlds/$W" | field deleted)" = True ] && ok "test world deleted" || bad "could not delete test world $W"
echo "$pass passed, $fail failed"
[ "$fail" = 0 ]
